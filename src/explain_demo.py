"""Measure what the indexes from sql/02_indexes.sql actually give.

For every query: drop the index, run EXPLAIN ANALYZE, create the index, run it
again, and write both plans to docs/query_optimization.md.

Usage:
    python src/explain_demo.py
"""

import re

from sqlalchemy import Connection, text

from db import PROJECT_DIR, get_engine

CASES = [
    {
        "title": "Call history of one customer",
        "why": "Opened by an agent every time a customer calls, so it must be instant.",
        "query": """
            SELECT call_id, started_at, status, talk_seconds
            FROM core.fact_call
            WHERE customer_id = 'C000123'
            ORDER BY started_at DESC
        """,
        "index_name": "idx_fact_call_customer_started",
        "index_sql": "CREATE INDEX idx_fact_call_customer_started ON core.fact_call (customer_id, started_at)",
    },
    {
        "title": "One agent's calls for one week",
        "why": "The base of weekly agent reports.",
        "query": """
            SELECT count(*), avg(talk_seconds)
            FROM core.fact_call
            WHERE agent_id = 'A007'
              AND started_at >= '2026-09-01' AND started_at < '2026-09-08'
        """,
        "index_name": "idx_fact_call_agent_started",
        "index_sql": "CREATE INDEX idx_fact_call_agent_started ON core.fact_call (agent_id, started_at)",
    },
    {
        "title": "All calls of one day",
        "why": "Daily operational report.",
        "query": """
            SELECT status, count(*)
            FROM core.fact_call
            WHERE started_at >= '2026-10-15' AND started_at < '2026-10-16'
            GROUP BY status
        """,
        "index_name": "idx_fact_call_started_at",
        "index_sql": "CREATE INDEX idx_fact_call_started_at ON core.fact_call (started_at)",
    },
]


def explain(conn: Connection, query: str) -> tuple[str, float]:
    """Return the plan and the execution time (best of 3 runs, to skip cold-cache noise)."""
    best_plan, best_ms = "", float("inf")
    for _ in range(3):
        plan = "\n".join(r[0] for r in conn.execute(text("EXPLAIN (ANALYZE, BUFFERS) " + query)))
        ms = float(re.search(r"Execution Time: ([\d.]+) ms", plan).group(1))
        if ms < best_ms:
            best_plan, best_ms = plan, ms
    return best_plan, best_ms


def main() -> None:
    engine = get_engine()
    lines = [
        "# Query optimization with indexes",
        "",
        "Generated by `python src/explain_demo.py` — these are real `EXPLAIN (ANALYZE, BUFFERS)` plans,",
        "not hand-written examples. Each query runs first without its index and then with it.",
        "",
    ]
    summary = ["| Query | Without index | With index | Speed-up |", "|---|---|---|---|"]
    details = []

    with engine.begin() as conn:
        n_rows = conn.execute(text("SELECT count(*) FROM core.fact_call")).scalar()
        version = conn.execute(text("SHOW server_version")).scalar()
        # Only the index under test may differ, so drop all three first
        for case in CASES:
            conn.execute(text(f"DROP INDEX IF EXISTS core.{case['index_name']}"))
        conn.execute(text("ANALYZE core.fact_call"))

        for case in CASES:
            plan_before, ms_before = explain(conn, case["query"])
            conn.execute(text(case["index_sql"]))
            conn.execute(text("ANALYZE core.fact_call"))
            plan_after, ms_after = explain(conn, case["query"])
            conn.execute(text(f"DROP INDEX core.{case['index_name']}"))

            summary.append(f"| {case['title']} | {ms_before:.3f} ms | {ms_after:.3f} ms "
                           f"| {ms_before / ms_after:.0f}x |")
            details += [
                f"## {case['title']}", "", case["why"], "",
                "```sql", "\n".join(l[12:] if l.startswith(" " * 12) else l
                                    for l in case["query"].strip("\n").splitlines()), "```", "",
                f"Index: `{case['index_sql']}`", "",
                f"**Before — {ms_before:.3f} ms**", "", "```", plan_before, "```", "",
                f"**After — {ms_after:.3f} ms**", "", "```", plan_after, "```", "",
            ]

        # Leave the database with all indexes in place
        for case in CASES:
            conn.execute(text(case["index_sql"]))

    lines += [f"Table `core.fact_call`: {n_rows:,} rows, PostgreSQL {version}.", ""] + summary + [""] + details
    out = PROJECT_DIR / "docs" / "query_optimization.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Written {out}")
    print("\n".join(summary))


if __name__ == "__main__":
    main()
